using System.Text;
using PlayFab.Cli.Models;

namespace PlayFab.Cli.Infrastructure;

public sealed record GeneratedPropertySpec(string PropertyName, string CSharpType, string OriginalColumnName);

public sealed record GeneratedClassSpec(
    string ClassName,
    string ConstName,
    string ConstValue,
    List<GeneratedPropertySpec> MetadataProperties,
    List<GeneratedPropertySpec> ColumnProperties);

/// <summary>
/// Pure logic turning a statistic/leaderboard desired-state definition into a C# class spec, and
/// rendering that spec as source text. No file I/O, no PlayFab calls — see Commands/Codegen for those.
/// </summary>
public static class CodeGenerator
{
    public static GeneratedClassSpec BuildStatisticClassSpec(StatisticDefinitionFile statistic)
    {
        var usedNames = new HashSet<string>();
        var columnProperties = statistic.Columns
            .Select(c => new GeneratedPropertySpec(
                DisambiguatePropertyName(SanitizeIdentifier(c.Name), usedNames), ResolveCSharpType(c.Type), c.Name))
            .ToList();

        return new GeneratedClassSpec(
            ClassName: SanitizeIdentifier(statistic.Name) + "Statistic",
            ConstName: "Name",
            ConstValue: statistic.Name,
            MetadataProperties: [],
            ColumnProperties: columnProperties);
    }

    public static GeneratedClassSpec BuildLeaderboardClassSpec(LeaderboardDefinitionFile leaderboard, List<StatisticDefinitionFile> statistics)
    {
        List<GeneratedPropertySpec> metadataProperties =
        [
            new("Rank", "int", "Rank"),
            new("EntityId", "string", "EntityId"),
            new("DisplayName", "string", "DisplayName"),
        ];

        // A column literally named "Rank"/"EntityId"/"DisplayName" would otherwise collide with the
        // metadata properties above and produce two same-named properties (doesn't compile).
        var usedNames = new HashSet<string>(metadataProperties.Select(p => p.PropertyName));
        var columnProperties = leaderboard.Columns
            .Select(c => new GeneratedPropertySpec(
                DisambiguatePropertyName(SanitizeIdentifier(c.Name), usedNames), ResolveLeaderboardColumnType(c, statistics), c.Name))
            .ToList();

        return new GeneratedClassSpec(
            ClassName: SanitizeIdentifier(leaderboard.Name) + "Entry",
            ConstName: "Name",
            ConstValue: leaderboard.Name,
            MetadataProperties: metadataProperties,
            ColumnProperties: columnProperties);
    }

    /// <summary>Appends "Column" (then "Column2", "Column3", ...) until the name is unique among already-assigned names.</summary>
    private static string DisambiguatePropertyName(string name, HashSet<string> usedNames)
    {
        if (usedNames.Add(name))
            return name;

        var candidate = name + "Column";
        var suffix = 2;
        while (!usedNames.Add(candidate))
        {
            candidate = name + "Column" + suffix;
            suffix++;
        }

        return candidate;
    }

    public static string Render(GeneratedClassSpec spec, string @namespace)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine();
        sb.AppendLine($"namespace {@namespace};");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {spec.ClassName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string {spec.ConstName} = \"{EscapeStringLiteral(spec.ConstValue)}\";");

        if (spec.MetadataProperties.Count > 0)
        {
            sb.AppendLine();
            foreach (var prop in spec.MetadataProperties)
                sb.AppendLine($"    public {prop.CSharpType} {prop.PropertyName} {{ get; set; }}{DefaultValueSuffix(prop.CSharpType)}");
        }

        if (spec.ColumnProperties.Count > 0)
        {
            sb.AppendLine();
            foreach (var prop in spec.ColumnProperties)
                sb.AppendLine($"    public {prop.CSharpType} {prop.PropertyName} {{ get; set; }}{DefaultValueSuffix(prop.CSharpType)}");
        }

        sb.AppendLine();
        sb.AppendLine($"    public static {spec.ClassName} FromScores(IReadOnlyList<string> scores)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return new {spec.ClassName}");
        sb.AppendLine("        {");
        for (var i = 0; i < spec.ColumnProperties.Count; i++)
        {
            var prop = spec.ColumnProperties[i];
            sb.AppendLine($"            {prop.PropertyName} = {ParseExpression(prop.CSharpType, $"scores[{i}]")},");
        }
        sb.AppendLine("        };");
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    public List<string> ToScores()");
        sb.AppendLine("    {");
        sb.AppendLine("        return");
        sb.AppendLine("        [");
        foreach (var prop in spec.ColumnProperties)
            sb.AppendLine($"            {FormatExpression(prop.CSharpType, prop.PropertyName)},");
        sb.AppendLine("        ];");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>null/unrecognized local type -> "string" (same default statistics already use when the YAML field is omitted).</summary>
    internal static string ResolveCSharpType(string? localType)
    {
        if (localType is null)
            return "string";

        return ValidationConstants.CSharpTypeByColumnType.TryGetValue(localType, out var csharpType) ? csharpType : "string";
    }

    private static string ResolveLeaderboardColumnType(LeaderboardColumnDefinition column, List<StatisticDefinitionFile> statistics)
    {
        if (column.Type is not null)
            return ResolveCSharpType(column.Type);

        if (column.LinkedStatistic is not null && column.LinkedStatisticColumn is not null)
        {
            var statistic = statistics.FirstOrDefault(s => string.Equals(s.Name, column.LinkedStatistic, StringComparison.OrdinalIgnoreCase));
            var linkedColumn = statistic?.Columns.FirstOrDefault(c => string.Equals(c.Name, column.LinkedStatisticColumn, StringComparison.OrdinalIgnoreCase));
            if (linkedColumn is not null)
                return ResolveCSharpType(linkedColumn.Type);
        }

        return "string";
    }

    internal static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder();
        foreach (var c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
                sb.Append(c);
        }

        var result = sb.ToString();
        if (result.Length == 0)
            return "Unnamed";

        if (char.IsDigit(result[0]))
            result = "_" + result;

        return result;
    }

    private static string DefaultValueSuffix(string csharpType) => csharpType == "string" ? " = \"\";" : "";

    private static string ParseExpression(string csharpType, string source) => csharpType switch
    {
        "string" => source,
        "bool" => $"bool.Parse({source})",
        _ => $"{csharpType}.Parse({source}, CultureInfo.InvariantCulture)",
    };

    private static string FormatExpression(string csharpType, string propertyName) => csharpType switch
    {
        "string" => propertyName,
        "bool" => $"{propertyName}.ToString()",
        _ => $"{propertyName}.ToString(CultureInfo.InvariantCulture)",
    };

    private static string EscapeStringLiteral(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
